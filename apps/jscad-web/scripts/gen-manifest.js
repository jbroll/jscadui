// Regenerates src/storage/manifest.js from src/storage/schema.js.
// The manifest is plain data, so rowboat.js can import it without pulling in
// @jbroll/rowboat-schema's zod 4 types (unparseable by the root TS 4.9 gate).
// Run: node scripts/gen-manifest.js
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compileSchema } from '@jbroll/rowboat-schema'
import { schema } from '../src/storage/schema.js'

const dir = dirname(fileURLToPath(import.meta.url))
const manifest = compileSchema(schema).manifest
const body = `// Generated by scripts/gen-manifest.js from schema.js. Do not edit by hand.
export const manifest = ${JSON.stringify(manifest, null, 2)}
`
writeFileSync(join(dir, '../src/storage/manifest.js'), body)
console.log(`wrote manifest with tables: ${manifest.map((t) => t.name).join(', ')}`)
